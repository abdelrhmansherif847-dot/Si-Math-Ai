  const caps = CAPABILITIES.map((c) => {
    const ev = c.evidence.map((e) => {
      const link = e.ref ? ` <a href="#${esc(e.ref)}">See the research →</a>` : '';
      return `        <li><span class="k-ev-tag k-ev-${e.type}">${EV_LABEL[e.type]}</span><span>${e.text}${link}</span></li>`;
    }).join('\n');

    return `    <div class="k-cap" id="${esc(c.id)}">
      <div class="k-cap-head">
        <span class="k-cap-icon" aria-hidden="true">${c.icon}</span>
        <h3>${esc(c.name)}</h3>
      </div>
      <div class="k-qa"><span class="k-qa-q">What is it?</span><p>${c.what}</p></div>
      <div class="k-qa"><span class="k-qa-q">Why does it exist?</span><p>${c.why}</p></div>
      <div class="k-qa"><span class="k-qa-q">How does it work?</span><p>${c.how}</p></div>
      <span class="k-qa-q">What evidence supports its value?</span>
      <ul class="k-ev-list">
${ev}
      </ul>
      <div class="k-honest"><p><strong>The limits of this evidence:</strong> ${c.honest}</p></div>
    </div>`;
  }).join('\n\n');

