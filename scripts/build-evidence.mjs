#!/usr/bin/env node
/**
 * build-evidence.mjs — generates the Evidence Center from
 * docs/knowledge/evidence-data.mjs.
 *
 * Emits:
 *   evidence.html    capability evidence + research foundations + how features are built
 *   changelog.html   version history, every entry traceable to a dated artefact
 *   roadmap.html     direction, explicitly not promises
 *
 *   node scripts/build-evidence.mjs          # write all three
 *   node scripts/build-evidence.mjs --check  # exit 1 if any is out of date
 *
 * Why generate: the evidence for a claim and the claim itself must not be able
 * to drift apart, and the changelog has to keep accepting entries for years
 * without anyone rebuilding a page by hand. Both are data problems, so both
 * live in a data file.
 *
 * scripts/validate-knowledge-layer.mjs runs the --check form in CI.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  CAPABILITIES, RESEARCH, CHANGELOG, CHANGELOG_ESTABLISHED, ROADMAP, NOT_ON_ROADMAP,
} from '../docs/knowledge/evidence-data.mjs';
import { SITE, CANONICAL_DEFINITION, nav, footer, headAssets, organizationNode } from './_page-shell.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, '..');
const check = process.argv.includes('--check');

const esc = (s) => String(s)
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const jsonForScriptTag = (v) =>
  JSON.stringify(v, null, 2).replace(/<\/(script)/gi, '<\\/$1');

