const crumb = (label) => `
<div class="k-wrap">
  <nav class="k-crumb" aria-label="Breadcrumb">
    <ol>
      <li><a href="index.html">Home</a></li>
      <li>${esc(label)}</li>
    </ol>
  </nav>
</div>
`;

const breadcrumbGraph = (file, label) => ({
  '@type': 'BreadcrumbList',
  '@id': `${SITE}/${file}#breadcrumb`,
  itemListElement: [
    { '@type': 'ListItem', position: 1, name: 'Home', item: `${SITE}/` },
    { '@type': 'ListItem', position: 2, name: label, item: `${SITE}/${file}` },
  ],
});

/* ── evidence.html ──────────────────────────────────────────────────────── */

const EV_LABEL = { mechanism: 'Mechanism', research: 'Research', record: 'Record' };

